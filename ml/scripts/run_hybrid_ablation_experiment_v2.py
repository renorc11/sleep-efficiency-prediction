def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.use_deterministic_algorithms(True, warn_only=True)
    torch.set_num_threads(1)


def target_bins(y: np.ndarray) -> np.ndarray:
    return np.select([y < 70, y < 85], [0, 1], default=2).astype(int)


def make_time_channels(sequence: np.ndarray) -> np.ndarray:
    """Return activity plus explicit circular clock-time channels."""
    bins = np.arange(sequence.shape[1], dtype=np.float32)
    sine = np.sin(2 * np.pi * bins / sequence.shape[1])
    cosine = np.cos(2 * np.pi * bins / sequence.shape[1])
    return np.stack([
        sequence.astype(np.float32),
        np.broadcast_to(sine, sequence.shape),
        np.broadcast_to(cosine, sequence.shape),
    ], axis=1).astype(np.float32)


class TabularMLP(nn.Module):
    """Approximately capacity-matched to the revised Hybrid (within 7%)."""
    def __init__(self, tabular_dim: int, output_mode: str = "linear") -> None:
        super().__init__()
        self.output_mode = output_mode
        self.network = nn.Sequential(
            nn.Linear(tabular_dim, 64), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(64, 64), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(64, 16), nn.ReLU(), nn.Linear(16, 1),
        )

    def forward(self, tabular: torch.Tensor, _: torch.Tensor | None = None) -> torch.Tensor:
        value = self.network(tabular).squeeze(1)
        return 100 * torch.sigmoid(value) if self.output_mode == "sigmoid100" else value


class SequenceCNN(nn.Module):
    def __init__(self, output_mode: str = "linear") -> None:
        super().__init__()
        self.output_mode = output_mode
        self.sequence_branch = nn.Sequential(
            nn.Conv1d(3, 8, kernel_size=5, padding=2), nn.ReLU(), nn.MaxPool1d(2),
            nn.Conv1d(8, 16, kernel_size=5, padding=2), nn.ReLU(),
            nn.AdaptiveAvgPool1d(8), nn.Flatten(),
        )
        self.head = nn.Sequential(nn.Linear(128, 32), nn.ReLU(), nn.Linear(32, 1))

    def forward(self, _: torch.Tensor | None, sequence: torch.Tensor) -> torch.Tensor:
        value = self.head(self.sequence_branch(sequence)).squeeze(1)
        return 100 * torch.sigmoid(value) if self.output_mode == "sigmoid100" else value


class ExistingHybrid(nn.Module):
    """Experimental reproduction of the deployed architecture; never production-loaded."""
    def __init__(self, tabular_dim: int) -> None:
        super().__init__()
        self.sequence_branch = nn.Sequential(
            nn.Conv1d(1, 8, kernel_size=5, padding=2), nn.ReLU(), nn.MaxPool1d(2),
            nn.Conv1d(8, 16, kernel_size=5, padding=2), nn.ReLU(),
            nn.AdaptiveAvgPool1d(8), nn.Flatten(),
        )
        self.tabular_branch = nn.Sequential(
            nn.Linear(tabular_dim, 32), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(32, 16), nn.ReLU(),
        )
        self.head = nn.Sequential(nn.Linear(144, 32), nn.ReLU(), nn.Linear(32, 1))

    def forward(self, tabular: torch.Tensor, sequence: torch.Tensor) -> torch.Tensor:
        return self.head(torch.cat([self.tabular_branch(tabular), self.sequence_branch(sequence)], dim=1)).squeeze(1)


class RevisedHybrid(nn.Module):
    def __init__(self, tabular_dim: int, output_mode: str) -> None:
        super().__init__()
        self.output_mode = output_mode
        self.sequence_branch = nn.Sequential(
            nn.Conv1d(3, 8, kernel_size=5, padding=2), nn.ReLU(), nn.MaxPool1d(2),
            nn.Conv1d(8, 16, kernel_size=5, padding=2), nn.ReLU(),
            nn.AdaptiveAvgPool1d(8), nn.Flatten(),
        )
        self.tabular_branch = nn.Sequential(
            nn.Linear(tabular_dim, 32), nn.ReLU(), nn.Dropout(0.1),
            nn.Linear(32, 16), nn.ReLU(),
        )
        self.head = nn.Sequential(nn.Linear(144, 32), nn.ReLU(), nn.Linear(32, 1))

    def forward(self, tabular: torch.Tensor, sequence: torch.Tensor) -> torch.Tensor:
        value = self.head(torch.cat([self.tabular_branch(tabular), self.sequence_branch(sequence)], dim=1)).squeeze(1)
        return 100 * torch.sigmoid(value) if self.output_mode == "sigmoid100" else value


def parameter_count(model: nn.Module) -> int:
    return sum(parameter.numel() for parameter in model.parameters())


def make_model(spec: ModelSpec, tabular_dim: int) -> nn.Module:
    if spec.family == "tabular_mlp":
        return TabularMLP(tabular_dim, spec.output_mode)
    if spec.family == "sequence_cnn":
        return SequenceCNN()
    if spec.family == "existing_hybrid":
        return ExistingHybrid(tabular_dim)
    if spec.family in {"revised_hybrid", "incremental_hybrid", "negative_control"}:
        return RevisedHybrid(tabular_dim, spec.output_mode)
    raise ValueError(f"No neural architecture for {spec.family}")


def loss_for(name: str) -> nn.Module:
    if name == "mse":
        return nn.MSELoss()
    if name == "huber":
        # Predeclared delta: one percentage point. It is never tuned on outer folds.
        return nn.HuberLoss(delta=1.0)
    raise ValueError(f"Unsupported loss: {name}")


def metrics(y: np.ndarray, prediction: np.ndarray) -> dict[str, float | int | dict[str, float]]:
    residual = prediction - y  # Positive values are over-prediction bias.
    result: dict[str, float | int | dict[str, float]] = {
        "mae": float(mean_absolute_error(y, prediction)),
        "median_absolute_error": float(median_absolute_error(y, prediction)),
        "rmse": float(np.sqrt(mean_squared_error(y, prediction))),
        "r2": float(r2_score(y, prediction)),
        "mean_prediction_bias": float(residual.mean()),
        "prediction_min": float(prediction.min()),
        "prediction_max": float(prediction.max()),
        "outside_physical_0_100": int(((prediction < 0) | (prediction > 100)).sum()),
        "outside_observed_50_98": int(((prediction < 50) | (prediction > 98)).sum()),
        "residual_distribution": {
            "mean": float(residual.mean()), "std": float(residual.std(ddof=1)),
            "median": float(np.median(residual)), "q05": float(np.quantile(residual, 0.05)),
            "q95": float(np.quantile(residual, 0.95)),
            "skew": float(pd.Series(residual).skew()),
        },
    }
    for name, mask in {
        "below_70": y < 70,
        "70_to_below_85": (y >= 70) & (y < 85),
        "85_and_above": y >= 85,
    }.items():
        result[f"range_{name}"] = {
            "n": int(mask.sum()),
            "mae": float(mean_absolute_error(y[mask], prediction[mask])),
            "rmse": float(np.sqrt(mean_squared_error(y[mask], prediction[mask]))),
        }
    return result


def bootstrap_ci(y: np.ndarray, prediction: np.ndarray, seed: int = 8741) -> dict[str, list[float]]:
    rng = np.random.default_rng(seed)
    n = len(y)
    values = {"mae": [], "rmse": [], "r2": []}
    for _ in range(BOOTSTRAP_SAMPLES):
        index = rng.integers(0, n, n)
        values["mae"].append(mean_absolute_error(y[index], prediction[index]))
        values["rmse"].append(np.sqrt(mean_squared_error(y[index], prediction[index])))
        values["r2"].append(r2_score(y[index], prediction[index]))
    return {key: [float(np.quantile(value, 0.025)), float(np.quantile(value, 0.975))] for key, value in values.items()}


def select_epoch(
    spec: ModelSpec,
    x_train: np.ndarray,
    sequence_train: np.ndarray,
    y_train: np.ndarray,
    x_inner: np.ndarray,
    sequence_inner: np.ndarray,
    y_inner: np.ndarray,
    seed: int,
) -> int:
    set_seed(seed)
    model = make_model(spec, x_train.shape[1]).train()
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = loss_for(spec.loss_name)
    x_train_t = torch.tensor(x_train, dtype=torch.float32)
    seq_train_t = torch.tensor(sequence_train, dtype=torch.float32)
    y_train_t = torch.tensor(y_train, dtype=torch.float32)
    x_inner_t = torch.tensor(x_inner, dtype=torch.float32)
    seq_inner_t = torch.tensor(sequence_inner, dtype=torch.float32)
    y_inner_t = torch.tensor(y_inner, dtype=torch.float32)
    best_epoch, best_loss, wait = 1, float("inf"), 0
    for epoch in range(1, MAX_EPOCHS + 1):
        model.train()
        order = torch.randperm(len(y_train_t))
        for start in range(0, len(order), BATCH_SIZE):
            batch = order[start:start + BATCH_SIZE]
            optimizer.zero_grad()
            loss = criterion(model(x_train_t[batch], seq_train_t[batch]), y_train_t[batch])
            loss.backward()
            optimizer.step()
        model.eval()
        with torch.no_grad():
            value = float(criterion(model(x_inner_t, seq_inner_t), y_inner_t).item())
        if value < best_loss:
            best_epoch, best_loss, wait = epoch, value, 0
        else:
            wait += 1
            if wait >= PATIENCE:
                break
    return best_epoch


def fit_neural_predict(
    spec: ModelSpec,
    x_outer: np.ndarray,
    sequence_outer: np.ndarray,
    y_outer: np.ndarray,
    x_validation: np.ndarray,
    sequence_validation: np.ndarray,
    inner_train_index: np.ndarray,
    inner_validation_index: np.ndarray,
    seed: int,
) -> tuple[np.ndarray, int, int]:
    scaler = StandardScaler().fit(x_outer[inner_train_index])
    best_epoch = select_epoch(
        spec,
        scaler.transform(x_outer[inner_train_index]), sequence_outer[inner_train_index], y_outer[inner_train_index],
        scaler.transform(x_outer[inner_validation_index]), sequence_outer[inner_validation_index], y_outer[inner_validation_index], seed,
    )
    scaler = StandardScaler().fit(x_outer)
    set_seed(seed)
    model = make_model(spec, x_outer.shape[1]).train()
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = loss_for(spec.loss_name)
    x_t = torch.tensor(scaler.transform(x_outer), dtype=torch.float32)
    sequence_t = torch.tensor(sequence_outer, dtype=torch.float32)
    y_t = torch.tensor(y_outer, dtype=torch.float32)
    for _ in range(best_epoch):
        order = torch.randperm(len(y_t))
        for start in range(0, len(order), BATCH_SIZE):
            batch = order[start:start + BATCH_SIZE]
            optimizer.zero_grad()
            loss = criterion(model(x_t[batch], sequence_t[batch]), y_t[batch])
            loss.backward()
            optimizer.step()
    model.eval()
    with torch.no_grad():
        prediction = model(
            torch.tensor(scaler.transform(x_validation), dtype=torch.float32),
            torch.tensor(sequence_validation, dtype=torch.float32),
        ).numpy()
    return prediction.astype(float), best_epoch, parameter_count(model)


def fit_tree_predict(spec: ModelSpec, x_train: np.ndarray, y_train: np.ndarray, x_validation: np.ndarray, seed: int) -> tuple[np.ndarray, int]:
    if spec.family == "rf":
        model = RandomForestRegressor(
            n_estimators=600, max_depth=10, min_samples_split=10,
            min_samples_leaf=1, random_state=seed, n_jobs=1,
        )
    elif spec.family == "xgb":
        model = XGBRegressor(
            objective="reg:squarederror", n_estimators=600, max_depth=5,
            learning_rate=0.1, subsample=0.7, colsample_bytree=1.0,
            min_child_weight=1, random_state=seed, tree_method="hist", n_jobs=1,
        )
    else:
        raise ValueError(spec.family)
    model.fit(x_train, y_train)
    return model.predict(x_validation).astype(float), 0


def feature_matrix(frame: pd.DataFrame, feature_set: str) -> np.ndarray:
    if feature_set == "safe9":
        return frame[SAFE_FEATURES].to_numpy(dtype=np.float32)
    if feature_set == "legacy20":
        return frame[LEGACY_FEATURES].to_numpy(dtype=np.float32)
    if feature_set == "none":
        return np.zeros((len(frame), 1), dtype=np.float32)
    raise ValueError(feature_set)


def sequence_for(spec: ModelSpec, raw: np.ndarray, time_channels: np.ndarray, outer_train_indices: np.ndarray, seed: int) -> np.ndarray:
    if spec.family == "existing_hybrid":
        return raw[:, None, :].astype(np.float32)
    if spec.family == "negative_control":
        # Preserve each row's activity count while disrupting within-day ordering.
        shuffled = raw.copy()
        rng = np.random.default_rng(seed + 50_000)
        for row in shuffled:
            rng.shuffle(row)
        return make_time_channels(shuffled)
    return time_channels


